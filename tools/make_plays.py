def dist(a, b):
    return math.hypot(a[0] - b[0], a[1] - b[1])


def ball_xy(ball, pos):
    return [pos[ball["holder"]][0] + 10, pos[ball["holder"]][1] - 10] if "holder" in ball else ball["point"]


def timing(a_pos, a_ball, b_pos, b_ball, shot):
    """Same as timing() in js/core.js."""
    moved = a_ball != b_ball
    d = dist(ball_xy(a_ball, a_pos), ball_xy(b_ball, b_pos)) if moved else 0
    run = max(dist(a_pos[k], b_pos[k]) for k in KEYS)
    run_ms = 450 + run * 8.5
    ball_ms, arc = 0, 0
    if moved:
        if shot == "shot":
            ball_ms, arc = 1100 + d * 2, min(80, max(40, d * 0.35))
        elif shot == "lob":
            ball_ms, arc = 900 + d * 4, min(70, max(35, d * 0.3))
        else:
            ball_ms, arc = 450 + d * 3.2, min(18, max(6, d * 0.1))
    return round(arc), round(min(3000, max(700, max(ball_ms, run_ms))))


PLAYS = []


def play(pid, name, folder, intro, start, holder, steps):
    pos = {k: list(v) for k, v in start.items()}
    assert sorted(pos) == sorted(KEYS), (pid, sorted(pos))
    ball = {"holder": holder}
    out = []
    for s in steps:
        moves = {k: list(v) for k, v in s.get("moves", {}).items()}
        new_pos = {**pos, **moves}
        b = s.get("ball")
        new_ball = ball if b is None else ({"point": BASKET[:]} if b == "ring" else {"holder": b})
        shot = "shot" if b == "ring" else s.get("shot")
        arc, dur = timing(pos, ball, new_pos, new_ball, shot)
        st = {"cap": s["cap"], "dur": int(dur * s.get("slow", 1)), "arc": arc, "moves": moves, "ball": None if new_ball == ball else new_ball}
        if shot:
            st["shot"] = shot
        if s.get("via"):
            st["via"] = {k: list(v) for k, v in s["via"].items()}
        if s.get("screens"):
            st["screens"] = s["screens"]
        out.append(st)
        pos, ball = new_pos, new_ball
    PLAYS.append({
        "format": 1, "id": pid, "name": name, "folder": folder, "intro": intro,
        "start": {"pos": {k: list(start[k]) for k in KEYS}, "ball": {"holder": holder}}, "steps": out,
    })


