def main():
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        if f.endswith(".json"):
            os.remove(os.path.join(OUT, f))
    order = ["01", "02", "03", "04", "06", "07", "08", "09", "10", "11", "12", "13", "14", "15", "16", "17", "18", "05"]
    plays = sorted(PLAYS, key=lambda p: (order.index(p["id"][:2]), p["id"]))
    index = {"folders": sorted({p["folder"] for p in plays} | {M_LOW, "Атака против зоны"}), "plays": []}
    for p in plays:
        folder = p.pop("folder")
        p["updated"] = "2026-11-10T00:00:00.000Z"
        with open(os.path.join(OUT, p["id"] + ".json"), "w", encoding="utf-8") as fh:
            json.dump(p, fh, ensure_ascii=False, indent=2)
            fh.write("\n")
        index["plays"].append({"id": p["id"], "name": p["name"], "folder": folder, "file": p["id"] + ".json", "updated": p["updated"]})
    with open(os.path.join(OUT, "index.json"), "w", encoding="utf-8") as fh:
        json.dump(index, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    print(f"{len(plays)} plays written to plays/")


if __name__ == "__main__":
    main()
