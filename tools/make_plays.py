"""Generate the animated plays (plays/*.json + plays/index.json) from the diagrams.

Usage: python3 tools/make_plays.py

Same coordinates as tools/make_diagrams.py (floor x 20–360, y 20–310, ring at 190, 292).
Each play: a starting position for all ten players and the ball, then steps. A step lists who
moves where (`via` = control point of a curved run), where the ball goes (a player, or "ring"
for a shot), the kind of ball ("lob" = high pass, "shot"), and who sets a screen.
Plays edited later in the web editor are saved over these files; re-running this script
overwrites them again.
"""
